import mongoose from "mongoose";

const orderSchema = new mongoose.Schema({
   customer:{
      type:mongoose.Schema.Types.ObjectId,
      ref:"User",
      required:true
   },
   farmer:{
      type:mongoose.Schema.Types.ObjectId,
      ref:"User",
      required:true
   },
   deliveryPartner:{
      type:mongoose.Schema.Types.ObjectId,
      ref:"Delivery",
      default:null
   },
   products:[
      {
         product:{
            type:mongoose.Schema.Types.ObjectId,
            ref:"Product",
            required:true
         },
         productName:{
            type:String,
            required:true
         },
         productImage:{
            type:String,
            default:""
         },
         quantity:{
            type:Number,
            required:true
         },
         price:{
            type:Number,
            required:true
         },
         total:{
            type:Number,
            required:true
         }
      }
   ],
   shippingAddress:{
      fullName:{
         type:String,
         required:true
      },
      phone:{
         type:String,
         required:true
      },
      address:{
         type:String,
         required:true
      },
      city:{
         type:String,
         required:true
      },
      state:{
         type:String,
         required:true
      },
      pincode:{
         type:String,
         required:true
      },
      latitude:{
          type:Number,
          default:null
      },
     longitude:{
        type:Number,
        default:null
     }
   },
   paymentMethod:{
      type:String,
      enum:["cod","online"],
      default:"cod"
   },
   paymentStatus:{
      type:String,
      enum:["pending","paid","failed"],
      default:"pending"
   },
   orderStatus:{
      type:String,
      enum:[
         "placed",
         "accepted",
         "packed",
         "shipped",
         "out_for_delivery",
         "delivered",
         "cancelled"
      ],
      default:"placed"
   },
   deliveryStatus:{
      type:String,
      enum:[
         "pending",
         "assigned",
         "accepted",
         "picked_up",
         "delivered"
      ],
      default:"pending"
   },
   totalProductPrice:{
      type:Number,
      required:true
   },

   deliveryCharge:{
      type:Number,
      default:0
   },
   totalAmount:{
      type:Number,
      required:true
   },
   deliveryOTP:{
      type:String,
      default:null
   },
   deliveredAt:{
      type:Date,
      default:null
   },
   cancelledAt:{
      type:Date,
      default:null
   }

},{timestamps:true});

const Order = mongoose.models.Order || mongoose.model("Order",orderSchema);
export default Order;